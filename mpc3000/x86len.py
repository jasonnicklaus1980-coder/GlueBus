"""Instruction-length decoder for the 8086/V53 subset used by the MPC3000 ROM.
Returns the length of the instruction at data[pos], or None if unknown."""
PREFIX = {0x26, 0x2E, 0x36, 0x3E, 0xF0, 0xF2, 0xF3}
def modrm_len(data, p):
    m = data[p]; mod = m >> 6; rm = m & 7; n = 1
    if mod == 3: return n
    if mod == 0 and rm == 6: return n + 2          # direct address
    if mod == 1: n += 1
    elif mod == 2: n += 2
    return n
def length(data, pos):
    p = pos
    while data[p] in PREFIX: p += 1
    op = data[p]; p += 1
    if op == 0x0F:                       # V53 extended opcodes: 0F xx imm8 (length taken from objdump)
        return p - pos + 2
    if op in (0x00,0x01,0x02,0x03,0x08,0x09,0x0A,0x0B,0x10,0x11,0x12,0x13,0x18,0x19,0x1A,0x1B,
              0x20,0x21,0x22,0x23,0x28,0x29,0x2A,0x2B,0x30,0x31,0x32,0x33,0x38,0x39,0x3A,0x3B,
              0x84,0x85,0x86,0x87,0x88,0x89,0x8A,0x8B,0x8C,0x8E,0x8D,0xC4,0xC5,0x62,
              0xD0,0xD1,0xD2,0xD3,0x62,0x63):
        return p - pos + modrm_len(data, p)
    if op in (0x04,0x0C,0x14,0x1C,0x24,0x2C,0x34,0x3C,0xA8,0xB0,0xB1,0xB2,0xB3,0xB4,0xB5,0xB6,0xB7,
              0xCD,0xE4,0xE5,0xE6,0xE7,0x6A,0x80,0x82,0x83,0xC0,0xC1,0xD4,0xD5):
        if op in (0x80,0x82,0x83,0xC0,0xC1):
            return p - pos + modrm_len(data, p) + 1
        return p - pos + 1
    if op in (0x05,0x0D,0x15,0x1D,0x25,0x2D,0x35,0x3D,0xA9,0xB8,0xB9,0xBA,0xBB,0xBC,0xBD,0xBE,0xBF,
              0xE8,0xE9,0x68,0x9A,0xEA,0xC2):
        return p - pos + (4 if op in (0x9A,0xEA) else 2)
    if op in (0xC6,0xC7,0x69,0x6B,0x81,0xF6,0xF7,0xFE,0xFF,0x8F,0xC8,0xC9):
        if op == 0xC8: return p - pos + 3
        if op == 0xC9: return p - pos
        n = p - pos + modrm_len(data, p)
        reg = (data[p] >> 3) & 7
        if op in (0xC6,0xC7): n += 1 if op == 0xC6 else 2
        if op in (0x69,0x81): n += 2
        if op == 0x6B: n += 1
        if op in (0xF6,) and reg in (0,1): n += 1
        if op in (0xF7,) and reg in (0,1): n += 2
        return n
    if op in (0x70,0x71,0x72,0x73,0x74,0x75,0x76,0x77,0x78,0x79,0x7A,0x7B,0x7C,0x7D,0x7E,0x7F,0xE0,0xE1,0xE2,0xE3,0xEB):
        return p - pos + 1
    if op in (0xA0,0xA1,0xA2,0xA3): return p - pos + 2
    if op in tuple(range(0x40,0x60)) + tuple(range(0x50,0x60)) + tuple(range(0x90,0x9A)) + tuple(range(0xAA,0xB0)) + tuple(range(0xD7,0xD8)) + \
            (0x90,0x98,0x99,0x9B,0x9C,0x9D,0x9E,0x9F,0xA4,0xA5,0xA6,0xA7,0xAC,0xAD,0xAE,0xAF,0xC3,0xCB,0xCC,0xCE,0xCF,
             0xD6,0xD7,0xEC,0xED,0xEE,0xEF,0xF4,0xF5,0xF8,0xF9,0xFA,0xFB,0xFC,0xFD,0xF1,0xD8,0xD9,0xDA,0xDB,0xDC,0xDD,0xDE,0xDF,
             0x6C,0x6D,0x6E,0x6F,0x9B):
        return p - pos
    return None
